	private final String label;
	private final String[] displayNames;

	TeleportItem(String label, String... aliases)
	{
		this.label = label;
		displayNames = new String[aliases.length + 1];
		displayNames[0] = label;
		System.arraycopy(aliases, 0, displayNames, 1, aliases.length);
	}

	public String label()
	{
		return label;
	}

	public static TeleportItem fromDisplayInfo(String displayInfo)
	{
		if (displayInfo == null || displayInfo.isBlank())
		{
			return null;
		}
		String clean = displayInfo.trim();
		for (TeleportItem item : values())
		{
			if (item.matches(clean))
			{
				return item;
			}
		}
		return null;
	}

	private boolean matches(String displayInfo)
	{
		for (String displayName : displayNames)
		{
			if (displayInfo.equals(displayName) || displayInfo.startsWith(displayName + ":"))
			{
				return true;
			}
		}
		return false;
	}
